    verifyTrue(testCase, isfield(burden.by_label, 'deep'));
    verifyTrue(testCase, isfield(burden.by_label, 'rapid'));
    verifyTrue(testCase, isfield(burden.by_label, 'irregular'));
    verifyTrue(testCase, isfield(burden.by_label, 'sigh'));
    verifyFalse(testCase, isfield(output, 'hyperventilation_syndrome'));
    verifyEqual(testCase, ...
        output.prespecified_db.hyperventilation_like.signal_assessment_status, ...
        'partial');
end

function testRapidDeepUsesJointAssessableDenominator(testCase)
    names = get_labels('short');
    mask = false(10, 11);
    rapid = strcmp(names, 'rapid');
    deep = strcmp(names, 'deep');
    mask(1:4, rapid) = true;
    mask(3:5, deep) = true;
    assessable = true(10, 11);
    assessable(6:10, deep) = false;
    overlap = compute_label_overlap_summary( ...
        mask, names, true(1, 11), 1, assessable, empty_events());
    verifyEqual(testCase, overlap.rapid_deep.overlap_duration_sec, 2);
    verifyEqual(testCase, overlap.rapid_deep.joint_assessable_duration_sec, 5);
    verifyEqual(testCase, ...
        overlap.rapid_deep.overlap_fraction_of_joint_assessable, 0.4);
    verifyEqual(testCase, ...
        overlap.rapid_deep.fraction_of_a_overlapped_by_b, 0.5);
    verifyNotEqual(testCase, ...
        overlap.rapid_deep.overlap_fraction_of_joint_assessable, ...
        overlap.rapid_deep.fraction_of_a_overlapped_by_b);
end

