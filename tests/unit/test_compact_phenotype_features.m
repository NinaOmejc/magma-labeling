function testRecordingScopeSummariesHonorLayerAssessability(testCase)
    [data, features, diagnostics, spo2_ref, config] = evidence_fixture();
    names = get_labels('short');
    available = true(1, 11);
    reasons = repmat({'available'}, 1, 11);
    mask = false(10, 11);
    events = empty_events();
    automatic_scope = true(10, 11);
    reviewed_scope = false(10, 11);
    reviewed_scope(1:5, :) = true;
    automatic_burden = compute_recording_label_burden( ...
        mask, names, available, events, 1, automatic_scope);
    reviewed_burden = compute_recording_label_burden( ...
        mask, names, available, events, 1, reviewed_scope);

    automatic = build_label_evidence_summary(names, available, reasons, ...
        data, features, spo2_ref, diagnostics, automatic_burden, config, ...
        mask, events, automatic_scope);
    reviewed = build_label_evidence_summary(names, available, reasons, ...
        data, features, spo2_ref, diagnostics, reviewed_burden, config, ...
        mask, events, reviewed_scope);

    verifyEqual(testCase, automatic.rapid.recording_median_rr_lungs, 20);
    verifyEqual(testCase, reviewed.rapid.recording_median_rr_lungs, 10);
    verifyEqual(testCase, automatic.deep.recording_median_ratio_lungs, 2);
    verifyEqual(testCase, reviewed.deep.recording_median_ratio_lungs, 1);
    verifyEqual(testCase, automatic.irregular.recording_median_cov_lungs, 0.3, ...
        'AbsTol', eps);
    verifyEqual(testCase, reviewed.irregular.recording_median_cov_lungs, 0.1, ...
        'AbsTol', eps);
    verifyEqual(testCase, ...
        automatic.thoracic.recording_median_thoracic_to_abdominal_ratio, 2);
    verifyEqual(testCase, ...
        reviewed.thoracic.recording_median_thoracic_to_abdominal_ratio, 1);
    verifyEqual(testCase, ...
        automatic.async.recording_median_absolute_phase_deg, 30);
    verifyEqual(testCase, ...
        reviewed.async.recording_median_absolute_phase_deg, 10);
end

