function testCompactCombinesBeltsAndKeepsZeroDistinctFromUnavailable(testCase)
    assessable = true(900, 11);
    [burden, overlap, evidence] = compact_fixture(900, assessable);
    compact = build_compact_phenotype_features(burden, overlap, evidence);
    validate_compact_phenotype_features(compact);
    verifyEqual(testCase, compact.values(4), 21);
    verifyEqual(testCase, compact.values(5), 1.5);
    verifyEqual(testCase, compact.values(10), 0.3, 'AbsTol', eps);
    verifyEqual(testCase, compact.values(12), 1.4);
    verifyEqual(testCase, compact.values(15), 35);
    verifyEqual(testCase, compact.values([13 16]), [0 0]);
    verifyTrue(testCase, all(compact.available([13 16])));

    names = get_labels('short');
    thoracic = strcmp(names, 'thoracic');
    async = strcmp(names, 'async');
    available = true(1, 11);
    available(thoracic | async) = false;
    evidence.rapid.recording_median_rr_diaph = NaN;
    evidence.deep.recording_median_ratio_diaph = NaN;
    burden_unavailable = compute_recording_label_burden(false(900, 11), ...
        names, available, empty_events(), 1, repmat(available, 900, 1));
    overlap_unavailable = compute_label_overlap_summary(false(900, 11), ...
        names, available, 1, repmat(available, 900, 1), empty_events());
    compact_unavailable = build_compact_phenotype_features( ...
        burden_unavailable, overlap_unavailable, evidence);
    verifyTrue(testCase, all(isnan(compact_unavailable.values(11:16))));
    verifyFalse(testCase, any(compact_unavailable.available(11:16)));
    verifyEqual(testCase, compact_unavailable.values(4), 20);
    verifyEqual(testCase, compact_unavailable.values(5), 1.4);
end

