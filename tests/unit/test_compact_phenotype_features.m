function output = event(type, start_index, end_index, fs)
    output = struct('type', type, 'start_idx', start_index, ...
        'end_idx', end_index, 'start_t', (start_index - 1) / fs, ...
        'end_t', end_index / fs, ...
        'duration', (end_index - start_index + 1) / fs);
end

