function testSchemaHasExactlyFixedUniqueTwentyOneFeatures(testCase)
    schema = get_phenotype_feature_schema();
    expected = { ...
        'db_hyperventilation_rapid_fraction', ...
        'db_hyperventilation_deep_fraction', ...
        'db_hyperventilation_rapid_deep_overlap_fraction', ...
        'db_hyperventilation_median_rr_bpm', ...
        'db_hyperventilation_median_relative_excursion', ...
        'db_periodic_deep_sighing_sighs_per_15_min', ...
        'db_periodic_deep_sighing_max_sighs_15_min', ...
        'db_periodic_deep_sighing_irregular_fraction', ...
        'db_periodic_deep_sighing_sigh_irregular_overlap_fraction', ...
        'db_periodic_deep_sighing_median_ibi_cov', ...
        'db_thoracic_dominant_fraction', ...
        'db_thoracic_dominant_median_ta_ratio', ...
        'db_thoracic_dominant_median_event_duration_sec', ...
        'db_asynchrony_fraction', ...
        'db_asynchrony_median_abs_phase_deg', ...
        'db_asynchrony_median_event_duration_sec', ...
        'pattern_apnea_fraction', 'pattern_periodic_fraction', ...
        'pattern_shallow_fraction', 'pattern_slow_fraction', ...
        'pattern_desaturation_fraction'};
    verifyEqual(testCase, schema.n_features, 21);
    verifyEqual(testCase, schema.feature_names, expected);
    verifyEqual(testCase, numel(unique(schema.feature_names)), 21);
    verifyEqual(testCase, nnz(strcmp(schema.feature_role, 'prespecified_db')), 16);
    verifyEqual(testCase, nnz(strcmp(schema.feature_role, 'additional_pattern')), 5);
    verifyFalse(testCase, any(contains(schema.feature_names, 'forced_abdominal')));
end

function testAdditionalPatternsAreNotDuplicated(testCase)
    [burden, overlap, evidence] = compact_fixture(900, true(900, 11));
    output = build_db_phenotype_evidence(burden, overlap, evidence);
    verifyEqual(testCase, fieldnames(output.respiratory_patterns), { ...
