        'async', struct('phase_coherence_mid', [0.7; 0.8; 0.9]), ...
        'periodic', struct('eami', struct( ...
            'time_sec', [0; 0.5; 1], ...
            'lungs', struct('index', [0.4; 0.6; 0.8]))));
    label_evidence_summary_automatic = struct( ...
        'version', 'test', 'deep', struct( ...
            'available', true, 'median_ratio_lungs', 1.4), ...
        'periodic', struct( ...
            'eami_event_count', 3, ...
            'eami_event_duration_sec', 360, ...
            'guyot_event_count', 2, ...
            'guyot_event_duration_sec', 180));
    label_evidence_summary_reviewed = struct( ...
        'version', 'test', 'deep', struct( ...
            'available', true, 'median_ratio_lungs', 1.5), ...
        'periodic', struct( ...
            'eami_event_count', 4, ...
            'eami_event_duration_sec', 480, ...
