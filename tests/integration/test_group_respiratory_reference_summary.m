function testDedicatedPhenotypeTablesUseFixedSchemaAndProvenance(testCase)
    results_root = tempname;
    subject_dir = fullfile(results_root, 'Sub1_M2');
    mkdir(subject_dir);
    cleanup_dir = onCleanup(@() rmdir(results_root, 's'));

    schema = get_phenotype_feature_schema();
    subject = 1;
    measure = 2;
    analysis_id = 'analysis_fixture';
    label_names = get_labels('short');
    label_available = true(1, 11);
    mask_automatic = false(20, 11);
    config = struct('fs', 10);
    automatic = compact_output(schema, [1:22 0.25 1]);
    reviewed = compact_output(schema, [101:122 0.75 0]);
    phenotypes = struct( ...
        'automatic', struct('numeric_summary', automatic), ...
        'reviewed', struct('numeric_summary', reviewed));
    save(fullfile(subject_dir, 'Sub1_M2_results.mat'), 'subject', 'measure', ...
        'analysis_id', 'label_names', 'label_available', 'mask_automatic', ...
        'config', 'phenotypes');

    build_group_label_table(results_root);
    out_dir = fullfile(results_root, 'group_analysis');
    all_layers = readtable(fullfile(out_dir, 'group_summary.xlsx'), ...
        'Sheet', 'Phenotypes', 'TextType', 'string', 'VariableNamingRule', 'preserve');
    auto = all_layers(all_layers.annotation_layer == "automatic", 2:end);
    review = all_layers(all_layers.annotation_layer == "reviewed", 2:end);
    cached = load(fullfile(out_dir, '_cache', 'group_analysis_data.mat'));
    availability = cached.cohort.phenotypes.availability_automatic;
    dictionary = readtable(fullfile(out_dir, 'group_details.xlsx'), ...
        'Sheet', 'Feature_dictionary', 'TextType', 'string', 'VariableNamingRule', 'preserve');

    expected_columns = [{'recording_id', 'subject', 'measure', ...
        'subject_group', 'analysis_id'}, schema.feature_names];
    verifyEqual(testCase, auto.Properties.VariableNames, expected_columns);
    verifyEqual(testCase, auto.recording_id, "Sub1_M2");
    verifyEqual(testCase, auto.analysis_id, "analysis_fixture");
    verifyEqual(testCase, table2array(auto(:, 6:end)), [1:22 0.25 1]);
    verifyEqual(testCase, table2array(review(:, 6:end)), [101:122 0.75 0]);
    verifyEqual(testCase, table2array(availability(:, 6:end)), ones(1, 24));
    verifyEqual(testCase, dictionary.feature_index, (1:24)');
    verifyEqual(testCase, dictionary.feature_name, ...
        string(schema.feature_names(:)));
    qc = readtable(fullfile(out_dir, 'group_details.xlsx'), 'Sheet', 'Phenotype_QC');
    verifyEqual(testCase, height(qc), 48);
    verifyTrue(testCase, isfile(fullfile(out_dir, '_cache', 'group_analysis_data.mat')));
end

function compact = compact_output(schema, values)
% COMPACT_OUTPUT Create one valid saved compact-vector fixture.

    compact = struct('version', 'magma_phenotype_numeric_summary_v4', ...
        'schema_version', schema.version, 'n_features', schema.n_features, ...
        'feature_names', {schema.feature_names}, 'values', double(values), ...
        'available', true(1, schema.n_features), ...
        'coverage_fraction', ones(1, schema.n_features), ...
        'missing_reason', {repmat({''}, 1, schema.n_features)}, ...
        'phenotype_group', {schema.phenotype_group}, ...
        'feature_role', {schema.feature_role}, 'units', {schema.units});
end

