function row = master_audit_entry(severity, issue, target, key, field, file, sheet, source_row, detail)
% MASTER_AUDIT_ENTRY Common, machine-readable integration audit schema.
    if nargin == 0
        row = table('Size',[0 9], 'VariableTypes', ...
            {'string','string','string','string','string','string','string','double','string'}, ...
            'VariableNames', {'severity','issue','table_name','key','field','source_file','source_sheet','source_row','detail'});
        return;
    end
    row = table(string(severity),string(issue),string(target),string(key), ...
        string(field),string(file),string(sheet),double(source_row),string(detail), ...
        'VariableNames', {'severity','issue','table_name','key','field','source_file','source_sheet','source_row','detail'});
end
