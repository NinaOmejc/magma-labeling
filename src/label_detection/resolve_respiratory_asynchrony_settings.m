function settings = resolve_respiratory_asynchrony_settings(config)
% RESOLVE_RESPIRATORY_ASYNCHRONY_SETTINGS Fill internal processing defaults.
% Explicit config.async values, including nested phase-offset overrides, win.
% Scientific controls remain visible in get_config_defaults; their fallbacks
% here also support direct detector calls with a partial configuration.

    defaults = struct( ...
        'analysis_fs', 20, ...
        'f0', 1, ...
        'min_dur_sec', 30, ...
        'fmin', 0.052, ...
        'fmax', 2.0, ...
        'low_mid_cut_hz', 0.145, ...
        'mid_high_cut_hz', 0.6, ...
        'tlphcoh_cycles', 10, ...
        'reference_mad_k', 3, ...
        'min_abs_drop', 0.15, ...
        'min_deviating_bins', 1, ...
        'plot_step_sec', 5, ...
        'plot_legacy_coherence', false);
    defaults.phase_offset = struct( ...
        'angle_threshold_deg', 30, ...
        'summary_cycles', 5, ...
        'min_resultant_length', 0.80, ...
        'min_valid_fraction', 0.80, ...
        'min_magnitude_fraction', 0.05, ...
        'frequency_min_hz', 0.052, ...
        'frequency_max_hz', 0.60, ...
        'frequency_tolerance_fraction', 0.30, ...
        'frequency_ratio_qc_range', [0.5 1.5], ...
        'lungs_polarity_multiplier', 1, ...
        'diaph_polarity_multiplier', 1, ...
        'edge_exclusion_cycles', 1);

    settings = defaults;
    names = fieldnames(defaults);
    for i = 1:numel(names)
        name = names{i};
        if ~strcmp(name, 'phase_offset')
            settings.(name) = get_config_value( ...
                config, 'async', name, defaults.(name));
        end
    end
    phase = get_config_value(config, 'async', 'phase_offset', struct());
    names = fieldnames(defaults.phase_offset);
    for i = 1:numel(names)
        name = names{i};
        if isfield(phase, name)
            settings.phase_offset.(name) = phase.(name);
        end
    end
end
