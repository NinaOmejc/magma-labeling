function manifest = build_group_descriptive_manifest(config, data) %#ok<INUSD>
% BUILD_GROUP_DESCRIPTIVE_MANIFEST List current outputs and cohort provenance.
    paths = string(data.files(:));
    if isfield(data, 'label_histograms')
        paths = [paths; string(data.label_histograms.distribution_figure)];
    end
    if isfield(data, 'group_histograms')
        paths = [paths; string(data.group_histograms.figures(:))];
    end
    paths = unique(paths(paths ~= ""), 'stable');
    n = numel(paths);
    manifest = table(paths, repmat(string(data.layer), n, 1), ...
        repmat(numel(data.subjects), n, 1), repmat(data.n_recordings, n, 1), ...
        repmat(numel(data.measures), n, 1), ...
        repmat(numel(data.excluded_subjects), n, 1), ...
        repmat(nnz(data.groups == "Control"), n, 1), ...
        repmat(nnz(data.groups == "Patient"), n, 1), ...
        repmat(nnz(data.groups == "Unknown"), n, 1), ...
        repmat(string(data.metadata_source), n, 1), ...
        repmat(string(data.metadata_file), n, 1), ...
        repmat(data.valid_measurement_pairs, n, 1), ...
        repmat(data.pair(1), n, 1), repmat(data.pair(2), n, 1), ...
        'VariableNames', {'generated_path', 'plot_layer', 'included_subjects', ...
        'included_recordings', 'included_measurements', 'excluded_subjects', ...
        'control_subjects', 'patient_subjects', 'unknown_subjects', ...
        'metadata_source', 'metadata_file', 'valid_measurement_pairs', ...
        'measurement_1', 'measurement_2'});
end
