        'Shallow-breathing duration divided by shallow-assessable duration.', ...
        'Slow-breathing duration divided by slow-assessable duration.', ...
        'Desaturation duration divided by desaturation-assessable duration.'};

    metadata_fields = {'feature_names', 'display_name', 'phenotype_group', ...
        'feature_role', 'units', 'source_description'};
    for i = 1:numel(metadata_fields)
        if numel(schema.(metadata_fields{i})) ~= schema.n_features
            error('MAGMA:PhenotypeFeatures:InvalidSchema', ...
                '%s must contain exactly %d entries.', ...
                metadata_fields{i}, schema.n_features);
        end
        schema.(metadata_fields{i}) = reshape( ...
            cellstr(string(schema.(metadata_fields{i}))), 1, []);
    end
    if numel(unique(schema.feature_names)) ~= schema.n_features
        error('MAGMA:PhenotypeFeatures:InvalidSchema', ...
            'Compact phenotype feature names must be unique.');
    end
end
