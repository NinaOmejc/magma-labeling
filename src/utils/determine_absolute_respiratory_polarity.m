function [data, trend, config] = determine_absolute_respiratory_polarity( ...
    data, trend, config, fs)
% DETERMINE_ABSOLUTE_RESPIRATORY_POLARITY Orient both belts by breath shape.
% Run after relative belt correction and before final cycle extraction. The
% landmarks measured here are temporary; downstream extraction detects them
% again on the final signals, including after a polarity flip.

    settings = struct('enabled', true, 'ratio_lower', 0.90, ...
        'ratio_upper', 1.10, 'majority_threshold', 0.65, ...
        'high_dwell_lower', 0.45, 'high_dwell_upper', 0.55, ...
        'min_valid_breaths', 10);
    if ~isfield(config, 'preprocessing') || ~isstruct(config.preprocessing)
        config.preprocessing = struct();
    end
    if isfield(config.preprocessing, 'absolute_polarity') && ...
            isstruct(config.preprocessing.absolute_polarity)
        provided = config.preprocessing.absolute_polarity;
        names = fieldnames(settings);
        for i = 1:numel(names)
            if isfield(provided, names{i}) && ~isempty(provided.(names{i}))
                settings.(names{i}) = provided.(names{i});
            end
        end
    end
    validate_settings(settings);
    config.preprocessing.absolute_polarity = settings;

    qc = struct( ...
        'absolute_polarity_checked', false, ...
        'absolute_polarity_flipped', false, ...
        'ie_ratio_lungs', NaN, ...
        'ie_ratio_diaphragm', NaN, ...
        'ie_ratio_combined', NaN, ...
        'shared_ie_ratio', NaN, ...
        'shared_fraction_insp_shorter', NaN, ...
        'shared_fraction_insp_longer', NaN, ...
        'shared_n_valid_breaths', 0, ...
        'shared_high_dwell_fraction', NaN, ...
        'shared_fraction_narrow_high', NaN, ...
        'shared_fraction_broad_high', NaN, ...
        'n_valid_breaths_lungs', 0, ...
        'n_valid_breaths_diaphragm', 0, ...
        'absolute_polarity_decision', 'insufficient_data', ...
        'channels_discordant', false, ...
        'channels_used', {{}});
    if ~settings.enabled
        config.preprocessing.absolute_polarity_qc = qc;
        log_message(config, 2, 'Absolute respiratory polarity: disabled.');
        return;
    end

    qc.absolute_polarity_checked = true;
    if isvector(data) || ~isfield(config, 'channels') || ...
            ~isscalar(fs) || ~isfinite(fs) || fs <= 0
        config.preprocessing.absolute_polarity_qc = qc;
        log_message(config, 1, ...
            'Absolute respiratory polarity: insufficient valid breaths, unchanged.');
        return;
    end

    % Use the same automatic peak/trough detector and respiratory QC settings
    % as the final extraction, without its plots or manual review.
    temporary_config = config;
    temporary_config.resp.do_plot = false;
    belts = {'lungs', 'diaph'};
    ratios = nan(1, 2);
    counts = zeros(1, 2);
    indices = nan(1, 2);
    for i = 1:2
        role = belts{i};
        has_field = ['has_' role];
        if strcmp(role, 'diaph')
            has_field = 'has_diaph';
        end
        idx_field = [role '_idx'];
        if ~isfield(config.channels, has_field) || ...
                ~config.channels.(has_field) || ...
                ~isfield(config.channels, idx_field)
            continue;
        end
        idx = config.channels.(idx_field);
        if ~isnumeric(idx) || ~isscalar(idx) || ~isfinite(idx) || ...
                idx ~= fix(idx) || idx < 1 || idx > size(data, 2) || ...
                any(indices(1:i-1) == idx)
            continue;
        end
        indices(i) = idx;
        if strcmp(role, 'lungs') && is_lung_belt_ignored(config)
            continue;
        end
        signal = data(:, idx);
        if nnz(isfinite(signal)) < 3
            continue;
        end
        landmarks = extract_respiration_feature( ...
            signal, temporary_config, role);
        [ratios(i), counts(i)] = median_ie_ratio( ...
            landmarks, signal, fs, config.resp.min_peak_dist_sec);
    end

    qc.ie_ratio_lungs = ratios(1);
    qc.ie_ratio_diaphragm = ratios(2);
    qc.n_valid_breaths_lungs = counts(1);
    qc.n_valid_breaths_diaphragm = counts(2);
    usable = counts >= settings.min_valid_breaths & isfinite(ratios);
    qc.channels_used = belts(usable);
    if any(usable)
        qc.ie_ratio_combined = median(ratios(usable));
        if all(usable)
            lungs_z = standardized_signal(data(:, indices(1)));
            diaph_z = standardized_signal(data(:, indices(2)));
            resp_common = (lungs_z + diaph_z) / 2;
            shared_landmarks = extract_respiration_feature( ...
                resp_common, temporary_config, 'common');
            [qc.shared_ie_ratio, qc.shared_n_valid_breaths, ...
                qc.shared_fraction_insp_shorter, ...
                qc.shared_fraction_insp_longer, ...
                qc.shared_high_dwell_fraction, ...
                qc.shared_fraction_narrow_high, ...
                qc.shared_fraction_broad_high] = median_ie_ratio( ...
                shared_landmarks, resp_common, fs, ...
                config.resp.min_peak_dist_sec, settings);
            qc.channels_discordant = ...
                (ratios(1) < settings.ratio_lower) ~= ...
                    (ratios(2) < settings.ratio_lower) || ...
                (ratios(1) > settings.ratio_upper) ~= ...
                    (ratios(2) > settings.ratio_upper);
            if qc.shared_n_valid_breaths < settings.min_valid_breaths
                qc.absolute_polarity_decision = 'insufficient_data';
            elseif qc.shared_high_dwell_fraction < settings.high_dwell_lower && ...
                    qc.shared_fraction_narrow_high >= settings.majority_threshold
                qc.absolute_polarity_decision = 'kept';
            elseif qc.shared_high_dwell_fraction > settings.high_dwell_upper && ...
                    qc.shared_fraction_broad_high >= settings.majority_threshold
                qc.absolute_polarity_decision = 'flipped';
            else
                qc.absolute_polarity_decision = 'ambiguous';
            end
        elseif qc.ie_ratio_combined < settings.ratio_lower
            qc.absolute_polarity_decision = 'kept';
        elseif qc.ie_ratio_combined > settings.ratio_upper
            qc.absolute_polarity_decision = 'flipped';
        else
            qc.absolute_polarity_decision = 'ambiguous';
        end
        if strcmp(qc.absolute_polarity_decision, 'flipped')
            for i = 1:2
                if ~isfinite(indices(i))
                    continue;
                end
                idx = indices(i);
                data(:, idx) = -data(:, idx);
                if ~isempty(trend) && ~isvector(trend) && ...
                        size(trend, 1) == size(data, 1) && ...
                        idx <= size(trend, 2)
                    trend(:, idx) = -trend(:, idx);
                end
            end
            qc.absolute_polarity_flipped = true;
        end
    end
    config.preprocessing.absolute_polarity_qc = qc;

    if all(usable) && ...
            strcmp(qc.absolute_polarity_decision, 'insufficient_data')
        log_message(config, 1, ...
            ['Absolute respiratory polarity: insufficient valid shared ' ...
             'breaths, unchanged (valid breaths = %d).'], ...
            qc.shared_n_valid_breaths);
    elseif strcmp(qc.absolute_polarity_decision, 'insufficient_data')
        log_message(config, 1, ...
            ['Absolute respiratory polarity: insufficient valid breaths, ' ...
             'unchanged (lungs = %d, diaphragm = %d).'], counts(1), counts(2));
    else
        label = qc.absolute_polarity_decision;
        if strcmp(label, 'flipped'), label = 'flipped both belts'; end
        if strcmp(label, 'ambiguous'), label = 'ambiguous, unchanged'; end
        if all(usable)
            support = max(qc.shared_fraction_narrow_high, ...
                qc.shared_fraction_broad_high);
            support_label = 'breaths favoring one shape';
            if strcmp(qc.absolute_polarity_decision, 'kept')
                support = qc.shared_fraction_narrow_high;
                support_label = 'breaths with narrow highs';
            elseif strcmp(qc.absolute_polarity_decision, 'flipped')
                support = qc.shared_fraction_broad_high;
                support_label = 'breaths with broad highs';
            end
            log_message(config, 1, ...
                ['Absolute respiratory polarity: %s (shared high dwell = %.2f; ' ...
                 '%s = %.0f%%; shared I:E = %.2f; valid breaths = %d).'], ...
                label, qc.shared_high_dwell_fraction, support_label, ...
                100 * support, qc.shared_ie_ratio, ...
                qc.shared_n_valid_breaths);
        else
            log_message(config, 1, ...
                ['Absolute respiratory polarity: %s (single-belt I:E = ' ...
                 '%.2f; valid breaths = %d; used: %s).'], ...
                label, qc.ie_ratio_combined, counts(usable), ...
                strjoin(qc.channels_used, ', '));
        end
    end
end

function [ratio, n_valid, fraction_shorter, fraction_longer, ...
        high_dwell_fraction, fraction_narrow_high, fraction_broad_high] = ...
        median_ie_ratio(b, signal, fs, min_breath_sec, settings)
% MEDIAN_IE_RATIO Measure timing and high-level dwell in complete breaths.

    ratio = NaN;
    n_valid = 0;
    fraction_shorter = NaN;
    fraction_longer = NaN;
    high_dwell_fraction = NaN;
    fraction_narrow_high = NaN;
    fraction_broad_high = NaN;
    if ~isfield(b, 'peak_idx') || ~isfield(b, 'trough_idx') || ...
            ~isfield(b, 'peak_val') || ~isfield(b, 'trough_val')
        return;
    end
    peaks = b.peak_idx(:);
    troughs = b.trough_idx(:);
    if numel(peaks) < 3 || numel(troughs) ~= numel(peaks) - 1
        return;
    end
    values = nan(numel(peaks) - 2, 1);
    high_dwell = nan(numel(peaks) - 2, 1);
    for i = 2:numel(peaks)-1
        before = troughs(i-1);
        peak = peaks(i);
        after = troughs(i);
        if ~all(isfinite([before peak after])) || ...
                ~all(isfinite([b.trough_val(i-1) b.peak_val(i) b.trough_val(i)])) || ...
                before < 1 || after > numel(signal) || ...
                ~(before < peak && peak < after) || ...
                ~all(isfinite(signal(before:after)))
            continue;
        end
        insp = (peak - before) / fs;
        exp = (after - peak) / fs;
        if insp <= 0 || exp <= 0 || insp + exp < min_breath_sec
            continue;
        end
        values(i-1) = insp / exp;
        if nargin >= 5
            mid_level = (b.peak_val(i) + ...
                (b.trough_val(i-1) + b.trough_val(i)) / 2) / 2;
            high_dwell(i-1) = mean(signal(before:after) > mid_level);
        end
    end
    valid = isfinite(values);
    high_dwell = high_dwell(valid);
    values = values(valid);
    n_valid = numel(values);
    if n_valid > 0
        ratio = median(values);
        fraction_shorter = mean(values < 1);
        fraction_longer = mean(values > 1);
        if nargin >= 5
            high_dwell_fraction = median(high_dwell);
            fraction_narrow_high = mean( ...
                high_dwell < settings.high_dwell_lower);
            fraction_broad_high = mean( ...
                high_dwell > settings.high_dwell_upper);
        end
    end
end

function standardized = standardized_signal(signal)
% STANDARDIZED_SIGNAL Z-score finite samples while preserving missing samples.

    standardized = nan(size(signal));
    finite = isfinite(signal);
    values = signal(finite);
    spread = std(values);
    if isempty(values) || ~isfinite(spread) || spread <= 0
        return;
    end
    standardized(finite) = (values - mean(values)) / spread;
end

function validate_settings(settings)
    if ~(islogical(settings.enabled) || isnumeric(settings.enabled)) || ...
            ~isscalar(settings.enabled) || ~isfinite(settings.enabled) || ...
            ~isnumeric(settings.ratio_lower) || ...
            ~isnumeric(settings.ratio_upper) || ...
            ~isscalar(settings.ratio_lower) || ...
            ~isscalar(settings.ratio_upper) || ...
            ~isfinite(settings.ratio_lower) || ...
            ~isfinite(settings.ratio_upper) || ...
            settings.ratio_lower <= 0 || ...
            settings.ratio_lower >= settings.ratio_upper || ...
            ~isnumeric(settings.majority_threshold) || ...
            ~isscalar(settings.majority_threshold) || ...
            ~isfinite(settings.majority_threshold) || ...
            settings.majority_threshold < 0 || ...
            settings.majority_threshold > 1 || ...
            ~isnumeric(settings.high_dwell_lower) || ...
            ~isscalar(settings.high_dwell_lower) || ...
            ~isfinite(settings.high_dwell_lower) || ...
            ~isnumeric(settings.high_dwell_upper) || ...
            ~isscalar(settings.high_dwell_upper) || ...
            ~isfinite(settings.high_dwell_upper) || ...
            settings.high_dwell_lower <= 0 || ...
            settings.high_dwell_lower >= 0.5 || ...
            settings.high_dwell_upper <= 0.5 || ...
            settings.high_dwell_upper >= 1 || ...
            ~isnumeric(settings.min_valid_breaths) || ...
            ~isscalar(settings.min_valid_breaths) || ...
            ~isfinite(settings.min_valid_breaths) || ...
            settings.min_valid_breaths < 1 || ...
            settings.min_valid_breaths ~= fix(settings.min_valid_breaths)
        error('MAGMA:Config:InvalidAbsolutePolarity', ...
            'Invalid config.preprocessing.absolute_polarity settings.');
    end
end
