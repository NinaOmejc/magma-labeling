function out = finalize_selected_label_results( ...
    data, resp_features, detections, config, selected_labels, existing_results)
% FINALIZE_SELECTED_LABEL_RESULTS Merge a selected detector subset safely.
% Existing non-selected automatic/reviewed annotations and detector products
% are preserved. Selected automatic annotations are replaced, while selected
% active review coverage is cleared so stale manual edits cannot be reapplied.
% With no existing result, unselected labels remain canonical but explicitly
% unavailable with reason not_computed.

    if nargin < 6 || isempty(existing_results)
        existing_results = struct();
    end
    labels = get_labels('short');
    selected_labels = resolve_selected_labels(struct( ...
        'execution', struct('selected_labels', {selected_labels})));
    selected = ismember(labels, selected_labels);
    unselected = ~selected;
    N = size(data, 1);
    has_existing = ~isempty(fieldnames(existing_results));
    if has_existing
        validate_existing_result(existing_results, labels, N);
    end

    events_automatic = combine_event_sets( ...
        detections.events, labels, selected, has_existing, config.fs);
    mask_automatic = events_to_time_mask( ...
        events_automatic, N, config);
    if has_existing
        mask_automatic(:, unselected) = ...
            logical(existing_results.mask_automatic(:, unselected));
    end

    [available_fresh, reasons_fresh] = compute_label_availability( ...
        labels, resp_features, detections.diagnostics.desat, ...
        detections.diagnostics.async, detections.diagnostics.apnea, ...
        detections.diagnostics.sigh, detections.diagnostics.periodic);
    [assessable_fresh, assessability_info] = ...
        compute_label_assessable_mask( ...
            data, labels, available_fresh, detections.diagnostics.async, ...
            resp_features.time_sec, config);

    if has_existing
        available = logical(existing_results.label_available(:)');
        availability_reason = reshape(cellstr(string( ...
            existing_results.label_availability_reason)), 1, []);
        assessable_mask = logical(existing_results.label_assessable_mask);
        available(selected) = available_fresh(selected);
        availability_reason(selected) = reasons_fresh(selected);
        assessable_mask(:, selected) = assessable_fresh(:, selected);
    else
        available = available_fresh;
        availability_reason = reasons_fresh;
        assessable_mask = assessable_fresh;
        available(unselected) = false;
        availability_reason(unselected) = {'not_computed'};
        assessable_mask(:, unselected) = false;
    end

    [events_reviewed, mask_reviewed, review_coverage_mask, review_status, ...
        review_scope, review_history, review_provenance, manual_label_edit] = ...
        merged_review_layer(existing_results, labels, selected, N);
    [reviewed_assessable_mask, reviewed_available, ...
        reviewed_availability_reason] = compute_reviewed_label_availability( ...
            available, availability_reason, assessable_mask, ...
            review_coverage_mask);
    if has_existing
        reviewed_available(unselected) = logical( ...
            existing_results.label_reviewed_available(unselected));
        reviewed_availability_reason(unselected) = reshape(cellstr(string( ...
            existing_results.label_reviewed_availability_reason(unselected))), ...
            1, []);
        reviewed_assessable_mask(:, unselected) = logical( ...
            existing_results.label_reviewed_assessable_mask(:, unselected));
    end

    log_message(config, 2, 'Rebuilding merged summaries...');
    burden_automatic = compute_recording_label_burden( ...
        mask_automatic, labels, available, events_automatic, ...
        config.fs, assessable_mask);
    overlap_automatic = compute_label_overlap_summary( ...
        mask_automatic, labels, available, config.fs, ...
        assessable_mask, events_automatic);
    evidence_automatic = build_label_evidence_summary( ...
        labels, available, availability_reason, data, resp_features, ...
        detections.spo2_ref, detections.diagnostics, burden_automatic, ...
        config, mask_automatic, events_automatic, assessable_mask);

    burden_reviewed = compute_recording_label_burden( ...
        mask_reviewed, labels, reviewed_available, events_reviewed, ...
        config.fs, reviewed_assessable_mask);
    overlap_reviewed = compute_label_overlap_summary( ...
        mask_reviewed, labels, reviewed_available, config.fs, ...
        reviewed_assessable_mask, events_reviewed);
    evidence_reviewed = build_label_evidence_summary( ...
        labels, reviewed_available, reviewed_availability_reason, ...
        data, resp_features, detections.spo2_ref, detections.diagnostics, ...
        burden_reviewed, config, mask_reviewed, events_reviewed, ...
        reviewed_assessable_mask);
    phenotype_evidence = build_db_phenotype_evidence_bundle( ...
        burden_automatic, overlap_automatic, evidence_automatic, ...
        burden_reviewed, overlap_reviewed, evidence_reviewed);

    out = struct( ...
        'label_names', {labels}, ...
        'events_automatic', events_automatic, ...
        'mask_automatic', logical(mask_automatic), ...
        'events_reviewed', events_reviewed, ...
        'mask_reviewed', logical(mask_reviewed), ...
        'review_coverage_mask', logical(review_coverage_mask), ...
        'review_status', {review_status}, ...
        'review_scope', review_scope, ...
        'review_history', review_history, ...
        'review_provenance', review_provenance, ...
        'available', logical(available), ...
        'availability_reason', {availability_reason}, ...
        'assessable_mask', logical(assessable_mask), ...
        'assessability_info', assessability_info, ...
        'reviewed_available', logical(reviewed_available), ...
        'reviewed_availability_reason', {reviewed_availability_reason}, ...
        'reviewed_assessable_mask', logical(reviewed_assessable_mask), ...
        'candidate_events', detections.candidate_events, ...
        'spo2_ref', detections.spo2_ref, ...
        'detector_diagnostics', detections.diagnostics, ...
        'burden_automatic', burden_automatic, ...
        'burden_reviewed', burden_reviewed, ...
        'overlap_automatic', overlap_automatic, ...
        'overlap_reviewed', overlap_reviewed, ...
        'evidence_automatic', evidence_automatic, ...
        'evidence_reviewed', evidence_reviewed, ...
        'db_phenotype_evidence', phenotype_evidence, ...
        'manual_label_edit', manual_label_edit);
end

function events = combine_event_sets(sets, labels, selected, has_existing, fs)
% COMBINE_EVENT_SETS Normalize fresh events while preserving saved event rows.

    events = normalize_event_types_and_meta(empty_events(), fs);
    for i = 1:numel(labels)
        if isfield(sets, labels{i}) && ~isempty(sets.(labels{i}))
            part = sets.(labels{i})(:);
            if ~has_existing || selected(i)
                part = normalize_event_types_and_meta(part, fs);
            else
                part = orderfields(part, events);
            end
            events = [events; part]; %#ok<AGROW>
        end
    end
end

function [events, mask, coverage, status, scope, history, provenance, edit] = ...
    merged_review_layer(existing, labels, selected, N)
% MERGED_REVIEW_LAYER Preserve non-selected review state and clear selected state.

    mask = false(N, numel(labels));
    coverage = false(N, numel(labels));
    status = repmat({'unreviewed'}, 1, numel(labels));
    events = empty_events();
    scope = 'explicitly_viewed_or_edited_regions_per_label';
    history = struct([]);
    provenance = empty_review_provenance();
    edit = struct();
    if isfield(existing, 'mask_reviewed')
        mask = logical(existing.mask_reviewed);
        coverage = logical(existing.review_coverage_mask);
        status = reshape(cellstr(string(existing.review_status)), 1, []);
        events = existing.events_reviewed;
        if isfield(existing, 'review_scope'), scope = existing.review_scope; end
        if isfield(existing, 'review_history'), history = existing.review_history; end
        if isfield(existing, 'review_provenance')
            provenance = existing.review_provenance;
        end
        if isfield(existing, 'manual_label_edit')
            edit = existing.manual_label_edit;
        end
    end
    mask(:, selected) = false;
    coverage(:, selected) = false;
    status(selected) = {'unreviewed'};
    if ~isempty(events)
        events = events(~ismember({events.type}, labels(selected)));
    end
    edit = clear_selected_edit_state(edit, labels(selected), selected, N, numel(labels));
end

function edit = clear_selected_edit_state(edit, selected_labels, selected, N, L)
% CLEAR_SELECTED_EDIT_STATE Keep history but remove selected active review state.

    if ~isstruct(edit) || ~isscalar(edit)
        edit = struct();
        return;
    end
    if isfield(edit, 'review_coverage_mask') && ...
            isequal(size(edit.review_coverage_mask), [N L])
        edit.review_coverage_mask(:, selected) = false;
    end
    defs = manual_label_definitions();
    selected_defs = defs(ismember({defs.type}, selected_labels));
    list_fields = {'reviewed_fields', 'reviewed_labels', ...
        'changed_fields', 'changed_labels', 'changed_plot_names'};
    selected_values = {{selected_defs.field}, {selected_defs.type}, ...
        {selected_defs.field}, {selected_defs.name}, {selected_defs.plot_name}};
    for i = 1:numel(list_fields)
        field = list_fields{i};
        if isfield(edit, field)
            values = cellstr(string(edit.(field)));
            edit.(field) = values(~ismember(values, selected_values{i}));
        end
    end
    if isfield(edit, 'status_by_label') && isstruct(edit.status_by_label)
        for i = 1:numel(selected_labels)
            edit.status_by_label.(selected_labels{i}) = 'unreviewed';
        end
    end
    if isfield(edit, 'review_coverage_mask')
        edit.applied_saved_edits = any(edit.review_coverage_mask(:));
    end
end

function provenance = empty_review_provenance()
% EMPTY_REVIEW_PROVENANCE Match the canonical no-review provenance schema.

    provenance = struct( ...
        'version', 'manual_review_provenance_v1', ...
        'latest_round_id', NaN, ...
        'latest_reviewer_role', 'none', ...
        'start_from', 'none', ...
        'source_review_round', NaN, ...
        'latest_source_analysis_id', '', ...
        'number_of_rounds', 0, ...
        'most_recent_round_id', NaN);
end

function validate_existing_result(existing, labels, N)
% VALIDATE_EXISTING_RESULT Require merge-critical canonical saved fields.

    required = {'label_names', 'mask_automatic', 'events_automatic', ...
        'mask_reviewed', 'events_reviewed', 'review_coverage_mask', ...
        'review_status', 'label_available', 'label_availability_reason', ...
        'label_assessable_mask', 'label_reviewed_available', ...
        'label_reviewed_availability_reason', ...
        'label_reviewed_assessable_mask'};
    missing = required(~isfield(existing, required));
    if ~isempty(missing)
        error('MAGMA:Execution:IncompleteExistingResult', ...
            'Existing result is missing merge field(s): %s.', ...
            strjoin(missing, ', '));
    end
    if ~isequal(cellstr(string(existing.label_names)), labels) || ...
            ~isequal(size(existing.mask_automatic), [N numel(labels)]) || ...
            ~isequal(size(existing.mask_reviewed), [N numel(labels)]) || ...
            ~isequal(size(existing.review_coverage_mask), [N numel(labels)]) || ...
            ~isequal(size(existing.label_assessable_mask), [N numel(labels)]) || ...
            ~isequal(size(existing.label_reviewed_assessable_mask), ...
                [N numel(labels)]) || ...
            numel(existing.label_available) ~= numel(labels) || ...
            numel(existing.label_availability_reason) ~= numel(labels) || ...
            numel(existing.label_reviewed_available) ~= numel(labels) || ...
            numel(existing.label_reviewed_availability_reason) ~= numel(labels) || ...
            numel(existing.review_status) ~= numel(labels)
        error('MAGMA:Execution:IncompatibleExistingResult', ...
            'Existing result does not match the canonical label/sample schema.');
    end
end
