function evidence = build_db_phenotype_evidence( ...
    label_burden, overlaps, label_evidence, source_provenance)
% BUILD_DB_PHENOTYPE_EVIDENCE Organize label metrics as descriptive phenotype evidence.
% label_burden, prespecified overlaps, and detector-specific label_evidence
% describe one annotation layer; source_provenance names that layer. evidence
% contains schema version/source, placeholder external_clinical_data, three
% interpretation levels, and five phenotype entries. Each entry stores name,
% signal assessability/evidence availability, signal-derived measures, required
% external data, limitations, source provenance, and integration status.

    if nargin < 4 || isempty(source_provenance)
        source_provenance = 'automatic_labels';
    end
    source_provenance = char(string(source_provenance));

    evidence = struct();
    evidence.version = 'magma_db_phenotype_evidence_v1';
    evidence.source_provenance = source_provenance;
    evidence.external_clinical_data = empty_external_clinical_data();
    evidence.levels = struct( ...
        'level_1', 'elementary physiological labels and evidence', ...
        'level_2', 'prespecified MAGMA DB phenotype evidence', ...
        'level_3', 'future data-driven phenotype discovery');

    hvs_measures = struct( ...
        'rapid_fraction', label_burden.by_label.rapid.fraction, ...
        'deep_fraction', label_burden.by_label.deep.fraction, ...
        'rapid_deep_overlap_fraction_of_rapid', ...
            overlaps.rapid_deep.fraction_of_a_overlapped_by_b, ...
        'rapid_deep_overlap_fraction_of_deep', ...
            overlaps.rapid_deep.fraction_of_b_overlapped_by_a, ...
        'median_rr_lungs', label_evidence.rapid.median_rr_lungs, ...
        'median_rr_diaph', label_evidence.rapid.median_rr_diaph, ...
        'median_deep_excursion_ratio_lungs', label_evidence.deep.median_ratio_lungs, ...
        'median_deep_excursion_ratio_diaph', label_evidence.deep.median_ratio_diaph);
    evidence.hyperventilation_syndrome = phenotype( ...
        'Hyperventilation syndrome', false, ...
        label_burden.by_label.rapid.available || label_burden.by_label.deep.available, ...
        hvs_measures, ...
        {'ETCO2_or_capnography', 'ventilation_relative_to_metabolic_demand', ...
         'cardiopulmonary_exercise_testing', 'clinical_assessment', ...
         'Nijmegen_Questionnaire'}, ...
        {'respiratory_pattern_support_only', ...
         'rapid_plus_deep_is_not_a_hyperventilation_diagnosis'});

    sigh_measures = struct( ...
        'sigh_count', label_burden.sigh_count, ...
        'sighs_per_15_min', label_burden.sighs_per_15_min, ...
        'irregular_fraction', label_burden.by_label.irregular.fraction, ...
        'deep_fraction', label_burden.by_label.deep.fraction, ...
        'fraction_of_sigh_overlapping_irregular', ...
            overlaps.sigh_irregular.fraction_of_a_overlapped_by_b);
    evidence.periodic_deep_sighing = phenotype( ...
        'Periodic deep sighing', true, ...
        label_burden.by_label.sigh.available && label_burden.by_label.irregular.available, ...
        sigh_measures, {}, ...
        {'continuous_pattern_evidence_without_a_clinical_cutoff', ...
         'distinct_from_periodic_breathing_label'});

    thor_measures = struct( ...
        'thoracic_dominance_fraction', label_burden.by_label.thoracic.fraction, ...
        'median_thoracic_to_abdominal_ratio', label_evidence.thoracic.median_ratio, ...
        'median_log_ratio', label_evidence.thoracic.median_log_ratio, ...
        'median_thoracic_relative_fraction', label_evidence.thoracic.median_relative_fraction);
    evidence.thoracic_dominant_breathing = phenotype( ...
        'Thoracic-dominant breathing', true, ...
        label_burden.by_label.thoracic.available, thor_measures, ...
        {'future_clinical_or_ergospirometric_validation'}, ...
        {'relative_within_record_change_from_independently_normalized_uncalibrated_belts', ...
         'not_calibrated_rib_cage_contribution'});

    evidence.forced_abdominal_expiration = phenotype( ...
        'Forced abdominal expiration', false, false, struct(), ...
        {'clinical_annotation_or_direct_abdominal_muscle_or_mechanical_evidence'}, ...
        {'belt_movement_cannot_establish_active_abdominal_muscle_recruitment', ...
         'future_kinematic_proxies_would_not_be_direct_muscle_evidence'});

    async_measures = struct( ...
        'asynchrony_fraction', label_burden.by_label.async.fraction, ...
        'analysis_valid', label_evidence.async.analysis_valid, ...
        'reference_coherence', label_evidence.async.reference_coherence, ...
        'median_observed_coherence', label_evidence.async.median_observed_coherence, ...
        'maximum_deviating_bins', label_evidence.async.maximum_deviating_bins);
    if isfield(label_evidence.async, 'primary_method')
        async_measures.primary_method = label_evidence.async.primary_method;
        async_measures.primary_available = ...
            label_evidence.async.primary_available;
    end
    phase_fields = {'phase_offset_available', 'median_absolute_phase_deg', ...
        'median_resultant_length', 'median_selected_resp_frequency_hz'};
    for i = 1:numel(phase_fields)
        if isfield(label_evidence.async, phase_fields{i})
            async_measures.(phase_fields{i}) = ...
                label_evidence.async.(phase_fields{i});
        end
    end
    evidence.thoracoabdominal_asynchrony = phenotype( ...
        'Thoraco-abdominal asynchrony', true, ...
        label_burden.by_label.async.available, async_measures, ...
        {'clinical_validation'}, ...
        {'algorithmic_wavelet_asynchrony_evidence_not_clinical_diagnosis', ...
         'distinct_from_thoracic_dominance'});

    phenotype_fields = {'hyperventilation_syndrome', 'periodic_deep_sighing', ...
        'thoracic_dominant_breathing', 'forced_abdominal_expiration', ...
        'thoracoabdominal_asynchrony'};
    for i = 1:numel(phenotype_fields)
        evidence.(phenotype_fields{i}).source_provenance = source_provenance;
        evidence.(phenotype_fields{i}).external_clinical_data_integrated = false;
    end
end

function out = phenotype(name, assessable, available, measures, required, limitations)
% PHENOTYPE Package one descriptive phenotype's evidence and limitations.
% measures is a signal-derived struct; required and limitations are cell arrays
% of external-data needs and interpretation constraints.

    out = struct( ...
        'name', name, ...
        'assessable_from_current_signals', logical(assessable), ...
        'evidence_available', logical(available), ...
        'signal_derived_measures', measures, ...
        'required_external_clinical_data', {required}, ...
        'limitations', {limitations});
end

function external = empty_external_clinical_data()
% EMPTY_EXTERNAL_CLINICAL_DATA Declare supported but not integrated clinical inputs.
% Each questionnaire/capnography/CPET/observation entry has available=false,
% empty value, and source='not_integrated'; status summarizes the whole struct.

    missing_entry = struct('available', false, 'value', [], 'source', 'not_integrated');
    external = struct( ...
        'status', 'not_integrated', ...
        'Nijmegen_Questionnaire', missing_entry, ...
        'ETCO2_or_capnography', missing_entry, ...
        'CPET_or_ergospirometry', missing_entry, ...
        'clinical_observations', missing_entry, ...
        'Beck_Anxiety_Inventory', missing_entry);
end
